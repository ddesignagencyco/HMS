// apps/api/scripts/supabase-buckets.mjs
//
// BE-006 / BE-034 (backend_requirement.md 3.1): creates (or corrects) the Supabase Storage buckets the API
// writes to, each PRIVATE, with a file-size limit and an allowed-MIME list.
//
// Why this exists: `createSignedUploadUrl` takes no size or type, so without a bucket-level limit anyone
// holding a signed upload URL can store any size and any type. The API now also checks size and type when a
// provider confirms a presigned document (provider-documents.service.ts), but the bucket is the backstop that
// applies to every route, including the ones that never call head().
//
// Idempotent: a missing bucket is created, an existing one is updated to the policy below. It never deletes
// a bucket or an object. Run it once per Supabase project (staging and production separately).
//
//   npm run storage:buckets -w @smart-home/api              # apply
//   npm run storage:buckets -w @smart-home/api -- --dry-run # print what would change, touch nothing
//
// Needs SUPABASE_URL and SUPABASE_SECRET_KEY (a service-role/secret key) in the environment. See
// docs-final/runbooks/supabase-buckets.md.

import { createClient } from '@supabase/supabase-js';

const MiB = 1024 * 1024;

const documentTypes = ['image/jpeg', 'image/png', 'image/webp', 'application/pdf', 'video/mp4', 'video/webm', 'video/quicktime'];
const evidenceTypes = ['image/jpeg', 'image/png', 'image/webp', 'image/gif', 'video/mp4', 'video/webm', 'video/quicktime'];

/** Must match the API: documentContentTypes / MAX_VIDEO_BYTES (provider-documents), the evidence MIME list (booking.schemas) and evidence.photo_max_bytes. */
export const bucketPolicies = (env) => [
  // Logical name `documents` maps to SUPABASE_STORAGE_BUCKET (supabase-storage.service.ts resolveBucket).
  { name: env.SUPABASE_STORAGE_BUCKET || 'verification-documents', fileSizeLimit: 50 * MiB, allowedMimeTypes: documentTypes },
  { name: 'evidence', fileSizeLimit: 50 * MiB, allowedMimeTypes: evidenceTypes },
  // Written by the telephony provider; audio only. 100 MiB covers a long call at modest bitrates. Confirm against your provider's format.
  { name: 'recordings', fileSizeLimit: 100 * MiB, allowedMimeTypes: ['audio/mpeg', 'audio/mp4', 'audio/wav', 'audio/x-wav', 'audio/ogg', 'audio/webm'] },
  // Generated by the API: CSV, XLSX and PDF reports.
  {
    name: 'reports',
    fileSizeLimit: 25 * MiB,
    allowedMimeTypes: ['text/csv', 'application/pdf', 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet']
  }
];

const dryRun = process.argv.includes('--dry-run');

const main = async () => {
  const url = process.env.SUPABASE_URL;
  const key = process.env.SUPABASE_SECRET_KEY;
  if (!url || !key) {
    process.stderr.write('SUPABASE_URL and SUPABASE_SECRET_KEY must be set.\n');
    process.exit(1);
  }
  const client = createClient(url, key, { auth: { persistSession: false, autoRefreshToken: false } });
  const { data: existing, error } = await client.storage.listBuckets();
  if (error) throw new Error(`Could not list buckets: ${error.message}`);
  const byName = new Map(existing.map(bucket => [bucket.name, bucket]));

  for (const policy of bucketPolicies(process.env)) {
    const options = { public: false, fileSizeLimit: policy.fileSizeLimit, allowedMimeTypes: policy.allowedMimeTypes };
    const present = byName.get(policy.name);
    const action = present === undefined ? 'create' : 'update';
    process.stdout.write(`${dryRun ? '[dry-run] ' : ''}${action} ${policy.name}: private, max ${policy.fileSizeLimit / MiB} MiB, ${policy.allowedMimeTypes.length} MIME types\n`);
    if (dryRun) continue;
    const result = present === undefined ? await client.storage.createBucket(policy.name, options) : await client.storage.updateBucket(policy.name, options);
    if (result.error) throw new Error(`${action} ${policy.name} failed: ${result.error.message}`);
  }
  process.stdout.write(dryRun ? 'Dry run: nothing changed.\n' : 'Buckets are in place.\n');
};

main().catch(error => {
  process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
  process.exit(1);
});
